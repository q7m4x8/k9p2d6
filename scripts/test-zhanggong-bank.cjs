const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const assert = require('node:assert/strict')
const { merge } = require('../bank-loader')

const repo = path.resolve(__dirname, '..')
const root = path.join(repo, 'data', 'zhanggong')
const read = file => JSON.parse(fs.readFileSync(file, 'utf8'))
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')
const original = path.join(repo, 'data', 'questions.json')
assert.equal(hash(original), '3d6c5a303810092b5f284d0c57dec487ac553de528777bec53d0fd4dc0240869', 'Existing political bank must stay byte-identical')
const base = read(original)
const bank = read(path.join(root, 'questions.json'))
const audit = read(path.join(root, 'source-audit.json'))
const adRemoval = read(path.join(root, 'ad-removal.json'))
assert.equal(bank.version, '20261125-2')
assert.equal(adRemoval.coordinateSystem, 'source-page-pixels')
assert.equal(adRemoval.approved, true)
assert(adRemoval.answerEntries.length > 0)
assert.equal(adRemoval.questionEntries.length, 0, 'Clean question crops were independently verified outside all advertising areas')
assert.equal(audit.sourceFiles.length, 14)
assert.equal(new Set(audit.sourceFiles.map(file => file.file)).size, 14)
assert(audit.sourceFiles.every(file => file.bytes > 0 && /^[a-f0-9]{64}$/.test(file.sha256)))
assert.equal(bank.questions.length, 304)
assert.equal(bank.albums.length, 1)
const album = bank.albums[0]
assert.equal(album.title, '张弓选词大典')
assert.equal(album.count, 304)
assert.equal(album.papers.length, 16)
assert.equal(album.referenceMode, 'original-annotated')
for (const [i, paper] of album.papers.entries()) {
  assert.equal(paper.name, `第${String(i + 1).padStart(2, '0')}套`)
  assert.equal(paper.count, i === 15 ? 4 : 20)
  assert.equal(bank.questions.filter(q => q.paper === paper.name).length, paper.count)
}
for (const [year, expected] of [[2026, 115], [2025, 189]]) {
  const rows = bank.questions.filter(q => q.sourceQuestion.year === year)
  assert.equal(rows.length, expected)
  assert.deepEqual(rows.map(q => q.sourceQuestion.number), Array.from({ length: expected }, (_, i) => i + 1))
  assert.equal(audit.answerKey[year].length, expected)
}
const assetReferences = new Set()
const audited = new Map(audit.questions.map(q => [q.id, q]))
for (const entry of adRemoval.answerEntries) {
  const source = audited.get(entry.qid)
  assert(source, entry.qid)
  assert(Number.isInteger(entry.part) && entry.part >= 1 && entry.part <= source.answerCrops.length)
  const crop = source.answerCrops[entry.part - 1]
  assert.equal(entry.pdfPage, crop.pdfPage)
  assert.equal(entry.note, crop.note)
  assert.equal(entry.rectPx.length, 4)
  assert(entry.rectPx.every(Number.isInteger))
  assert(entry.rectPx[0] >= 0 && entry.rectPx[1] >= 0 && entry.rectPx[2] <= crop.pageWidthPx && entry.rectPx[3] <= crop.pageHeightPx)
}
for (const [i, q] of bank.questions.entries()) {
  const source = audited.get(q.id)
  assert(source, q.id)
  assert.equal(q.number, i + 1)
  assert.equal(q.paper, `第${String(Math.floor(i / 20) + 1).padStart(2, '0')}套`)
  assert.equal(q.id, `zg-${source.year}-${String(source.number).padStart(3, '0')}`)
  assert.equal(q.referenceMode, 'original-annotated')
  assert.equal(q.questionRenderMode, 'text')
  assert(q.stem.startsWith(`（${source.year}`) && q.stem.includes('____'), `${q.id}: full stem and blanks`)
  assert.equal(q.options.length, 4)
  assert(q.options.every(option => option.trim().length >= 2), `${q.id}: full option text`)
  assert.equal(q.explanation, '')
  assert.equal(q.answerLetter, audit.answerKey[source.year][source.number - 1])
  assert.equal(q.answer, 'ABCD'.indexOf(q.answerLetter))
  assert.equal(source.answerSource.pdfPage, source.year === 2026 ? 50 : 123)
  assert(q.questionImage.width > 0 && q.questionImage.height > 0)
  assetReferences.add(`questions/${q.questionImage.file}`)
  assert(q.referenceImages.length > 0)
  assert.equal(q.referenceImages.length, source.answerCrops.length)
  assert(source.answerCrops.every(crop => Array.isArray(crop.advertisingRemoved)))
  for (const image of q.referenceImages) {
    assert(/^[a-zA-Z0-9_-]+\.webp$/.test(image.file))
    assert(image.width > 0 && image.height > 0 && image.page > 0)
    assetReferences.add(`answers/${image.file}`)
  }
}
assert.equal(audited.size, 304)
const firstQuestion = bank.questions[0]
assert.match(firstQuestion.stem, /“办不成事”窗口冷清/)
assert.match(firstQuestion.stem, /依次填入画横线部分最恰当的一项是：/)
assert.deepEqual(firstQuestion.options, ['写照　托底', '成效　精准', '证明　应有', '缩影　必要'])
assert.match(bank.questions.find(q => q.id === 'zg-2025-028').stem, /甚至会____。/)
assert.match(bank.questions.find(q => q.id === 'zg-2026-113').stem, /相关研究仍然____。/)
assert.equal(audit.assets.length, assetReferences.size)
for (const asset of audit.assets) {
  assert(assetReferences.has(asset.file), `Unreferenced asset ${asset.file}`)
  const file = path.join(root, asset.file)
  assert.equal(fs.statSync(file).size, asset.bytes, asset.file)
  assert.equal(hash(file), asset.sha256, asset.file)
}
const conflicts = bank.questions.filter(q => q.sourceNotice)
assert.deepEqual(conflicts.map(q => q.id), ['zg-2025-081'])
assert.equal(conflicts[0].answerLetter, 'D')
assert.match(conflicts[0].sourceNotice, /B/)
assert.match(conflicts[0].sourceNotice, /D/)
const combined = merge([base, bank])
assert.deepEqual(combined.stats, { questionCount: 1404, paperCount: 71, albumCount: 6 })
assert.equal(new Set(combined.questions.map(q => q.id)).size, 1404)
assert.deepEqual(combined.questions.slice(0, 1100), base.questions)
assert.throws(() => merge([base, base]), /重复/)
assert.throws(() => merge([{ albums: [], questions: [{ id: 'orphan', album: 'missing' }] }]), /所属/)
